//! Print text as a scaled bitmap on the TM-U220.
//!
//! Instead of the printer's built-in characters, this renders an embedded 8x8
//! pixel font into a [`Bitmap`] and prints it via the `ESC *` bit-image path.
//! That lets us scale glyphs to arbitrary sizes by integer factors, far larger
//! than the hardware's text modes allow.
//!
//! Tuning knobs are the consts below. Note the printed pixels are not square:
//! vertical is ~72 dpi while horizontal is ~60 dpi in `MODE` 0, so equal
//! `SCALE_X`/`SCALE_Y` print slightly wider than tall. Bump `SCALE_X` down or
//! switch to `MODE` 1 if you want squarer characters.

use demo::graphics::{Bitmap, print_bitmap};
use eyre::Result;

/// Printable width in dot columns. The TM-U220's printable area is only ~1.5"
/// wide, so large characters fit just a few per line.
const PRINT_WIDTH: usize = 200;
/// `ESC *` mode (0 = single density ~60 dpi, 1 = double density ~120 dpi).
const MODE: u8 = 0;
/// Per-band line feed pitch in 1/144" units (see the graphics example).
const BAND_FEED: u8 = 16;

/// Horizontal glyph scale factor (each font pixel becomes `SCALE_X` dots wide).
const SCALE_X: usize = 4;
/// Vertical glyph scale factor (each font pixel becomes `SCALE_Y` dots tall).
const SCALE_Y: usize = 4;
/// Blank dots between adjacent glyphs.
const LETTER_SPACING: usize = SCALE_X;
/// Blank dots between wrapped text lines.
const LINE_GAP: usize = SCALE_Y * 2;

/// The string to print. `\n` forces a line break; long lines wrap on character
/// boundaries at `PRINT_WIDTH`.
const TEXT: &str = "Hello,\nTM-U220!";

fn main() -> Result<()> {
    let bitmap = render_text(TEXT);
    print_bitmap(&bitmap, MODE, BAND_FEED)?;
    Ok(())
}

/// Position of one glyph in the output bitmap.
struct Placed {
    x: usize,
    y: usize,
    ascii: u8,
}

/// Lay out `text` into glyph positions, wrapping at `PRINT_WIDTH` and on `\n`.
/// Returns the placements and the total bitmap height needed.
fn layout(text: &str) -> (Vec<Placed>, usize) {
    let glyph_w = 8 * SCALE_X;
    let glyph_h = 8 * SCALE_Y;

    let mut placed = Vec::new();
    let mut x = 0;
    let mut y = 0;

    for ch in text.chars() {
        if ch == '\n' {
            x = 0;
            y += glyph_h + LINE_GAP;
            continue;
        }

        // Map to printable ASCII; substitute anything else with '?'.
        let code = ch as u32;
        let ascii = if (0x20..=0x7E).contains(&code) {
            code as u8
        } else {
            b'?'
        };

        if x + glyph_w > PRINT_WIDTH {
            x = 0;
            y += glyph_h + LINE_GAP;
        }

        placed.push(Placed { x, y, ascii });
        x += glyph_w + LETTER_SPACING;
    }

    (placed, y + glyph_h)
}

/// Render `text` into a 1-bit bitmap using the embedded scaled font.
fn render_text(text: &str) -> Bitmap {
    let (placed, height) = layout(text);
    let mut bmp = Bitmap::new(PRINT_WIDTH, height);
    for glyph in &placed {
        draw_glyph(&mut bmp, glyph.ascii, glyph.x, glyph.y);
    }
    bmp
}

/// Blit one printable-ASCII glyph into `bmp` at `(ox, oy)`, scaled by
/// `SCALE_X`/`SCALE_Y`. In the font data the least significant bit is the
/// leftmost column.
fn draw_glyph(bmp: &mut Bitmap, ascii: u8, ox: usize, oy: usize) {
    let rows = &FONT8X8[(ascii - 0x20) as usize];
    for (row, bits) in rows.iter().enumerate() {
        for col in 0..8 {
            if (bits >> col) & 1 == 1 {
                for dy in 0..SCALE_Y {
                    for dx in 0..SCALE_X {
                        let x = (ox + col * SCALE_X + dx) as isize;
                        let y = (oy + row * SCALE_Y + dy) as isize;
                        bmp.set(x, y);
                    }
                }
            }
        }
    }
}

